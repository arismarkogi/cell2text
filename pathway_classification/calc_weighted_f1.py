def analyze_predictions_detailed(y_true, y_pred, pathway_names=None):
    """Provide detailed analysis of predictions"""
    print("\n" + "="*60)
    print("DETAILED PREDICTION ANALYSIS")
    print("="*60)
    
    num_samples, num_pathways = y_true.shape
    
    # Per-pathway analysis
    print(f"\nPer-pathway analysis:")
    print("-" * 40)
    
    for i in range(min(num_pathways, 10)):  # Show first 10 pathways
        pathway_name = f"Pathway {i}" if pathway_names is None else pathway_names[i]
        
        true_pos = np.sum((y_true[:, i] == 1) & (y_pred[:, i] == 1))
        false_pos = np.sum((y_true[:, i] == 0) & (y_pred[:, i] == 1))
        false_neg = np.sum((y_true[:, i] == 1) & (y_pred[:, i] == 0))
        true_neg = np.sum((y_true[:, i] == 0) & (y_pred[:, i] == 0))
        
        precision = true_pos / (true_pos + false_pos) if (true_pos + false_pos) > 0 else 0
        recall = true_pos / (true_pos + false_neg) if (true_pos + false_neg) > 0 else 0
        f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0
        
        print(f"{pathway_name}: TP={true_pos}, FP={false_pos}, FN={false_neg}, "
              f"P={precision:.3f}, R={recall:.3f}, F1={f1:.3f}")
    
    if num_pathways > 10:
        print(f"... and {num_pathways - 10} more pathways")


